def _draws(ids):
    """The router's seeded draws (§6.5, §6.1) on ``ids`` given in two orders: twins and yoked donors, as digests."""
    unit, kinds = "smoke/s0/determinism", {"fx-note": "withhold", "fx-print": "restore"}
    firing, items, donors = {"fx-note": ids, "fx-print": ids[::2]}, ids[::2], ids[1::2]
    found = []
    for order in (list, lambda listed: listed[::-1]):
        twins = router.draw_twins({k: order(v) for k, v in firing.items()}, list(kinds), kinds, unit)
        found.append(digest({"twins": twins, "yoke": router.yoke(order(items), order(donors), unit)}))
    return found


def _determinism(deps, item_files, scratch):
    package = fixtures.fixture_package()
    views = {bench: [solver.routing_view(bench, i["public"], runtime=fixtures.SHEET_RUNTIME)
                     for i in read_json(path)[:3]] for bench, path in sorted(item_files.items()) if bench != "alfworld"}
    runs, seeds = [], []
    for seed, reverse in ((0, False), (1, True)):
        worker = sandbox.Worker(docker=deps.docker, scratch=scratch, hashseed=seed).start(package, kind="cell")
        try:
            runs.append(fixtures.determinism_hashes(worker, package, views, reverse=reverse))
            seeds.append(worker.ping()["hashseed"])
        finally:
            worker.close()
    draws = _draws(sorted(i["task_id"] for i in read_json(item_files["searchqa"])))
    passed = runs[0] == runs[1] and seeds == ["0", "1"] and draws[0] == draws[1]
    return passed, {"hashes": len(runs[0]), "equal": runs[0] == runs[1], "seeds": seeds, "draws": draws,
                    "faults": sorted(k for k, v in runs[0].items() if v.startswith("fault:"))}


def _measure(deps, *, pinned, selftest, item_files, scratch):
    views = pool_views(pinned) if pinned is not None else deps.extra["pool_views"]()
    worker = sandbox.Worker(docker=deps.docker, scratch=scratch).start(fixtures.fixture_package(), kind="cell")
    started = deps.clock()
    try:
        ping = worker.ping()
        latency = round(deps.clock() - started, 3)
        call = worker.call("fx-note", "applies", [{"text": "fixture view 2019 1000"}], timeout_s=2)
    finally:
        worker.close()
    biggest = deps.extra["largest_workbook"]
    peak = deps.native_peak(biggest) if deps.native_peak else native_peak(biggest, deps.docker)
    tested = protocol.verified(read_json(selftest), "sandbox-selftest")["measured"]
    measured = {"vsz_kib": max(ping["vsz_kib"], tested["vsz_kib"]), "worker_rss_kib": max(ping["rss_kib"],
                                                                                        tested["rss_kib"]),
                "call_rss_kib": call.get("rss_kib") or 0, "native_peak_rss_kib": peak,
                "view_bytes_max": max(v["max"] for b, v in views.items() if b != "workbook"),
                "start_seconds": latency}
    available = (deps.mem_available_kib or _mem_available_kib)()
    derived = limits(measured, mem_available_kib=available)
    pins = {"limits": derived["limits"],
            "measured": {"vsz_kib": tested["vsz_kib"], "rss_kib": tested["rss_kib"],
                         "view_bytes_p99": tested["view_bytes_p99"], "native_peak_rss_kib": peak}}
    spec_limits = protocol.verified(read_json(selftest), "sandbox-selftest")["limits"]
    passed = derived["guard"]["ok"] and spec_limits == derived["limits"] and ping.get("dumpable") == 0
    return passed, {"measured": measured, "views": views, "derived": derived, "pins": pins,
                    "dumpable": ping.get("dumpable"), "p99_workbook_bytes": views["workbook"]["p99"],
                    "spec_limits_equal_derived": spec_limits == derived["limits"]}


def collect(root, *, snapshot=protocol.SNAPSHOT_ROOT, items, fixtures_dir, pins_out, selftest, manifest_path=None,
            traces=D3_TRACES, sheet_source=None, sheet_sha256=None, history_root=protocol.HISTORY_ROOT,
            exclusion_check=None, cards=None, runtimes=None, fake=False, deps=None, scratch="/tmp",
            engine_qualification=None):
    """Every S0 row once (module docstring); writes ``<root>/s0/s0-<row>.json``, ``<root>/s0/s0-limits.json``,
    ``pins_out`` ({"limits", "measured"} for ``make-manifest``) and ``<root>/s0/checks.json``. ``items``: {set: smoke
    item file} (``smoke.ITEM_SETS``); ``fixtures_dir``: ``make-fixtures``' output; ``selftest``: the sealed
    ``sandbox-selftest`` record (its measured values are the spec's, so the pins repeat them); ``manifest_path``: the
    v3 manifest whose ``data`` pins the training pools and whose ``runtime.spreadsheetbench`` is the base of the sheet
    row's runtime; ``engine_qualification``: the new zero-call v7 engine qualification of this snapshot (ticket
    C7b1-3), required with the v3 manifest and the v3 training qualification on the real path, checked before any row
    runs (S0 is collected once); ``exclusion_check(root)``: raises ValueError unless the persisted exclusion records
    verify (the CLI's ``exclusion_records``). Returns {"checks", "passed"}."""
    root = safe_path(root)
    require(not (root / DIR / CHECKS).exists(), "S0 is collected once per smoke root")
    require(set(items) == set(smoke.ITEM_SETS), "One smoke item file per set: %s" % (smoke.ITEM_SETS,))
    deps = deps or (fake_deps(scratch) if fake else Deps(docker=sandbox.Docker()))
    require(deps.engine_runtime is not None or all((engine_qualification, manifest_path, sheet_source, sheet_sha256)),
            "The real sheet row needs the new engine qualification (--engine-qualification, ticket C7b1-3), the v3 "
            "manifest and the v3 training qualification with its pinned record hash")
    deps.extra.setdefault("largest_workbook", max(
        (p for p in Path(fixtures_dir, fixtures.SHEET_DIR).glob("*/*_input.xlsx")), key=lambda p: p.stat().st_size))
    if deps.native is not None:  # the rehearsal's fake native runner: its stand-in cards and runtimes by default
        cards = REHEARSAL_CARDS if cards is None else cards
        runtimes = REHEARSAL_RUNTIMES if runtimes is None else runtimes
    require(cards is not None and runtimes is not None, "S0's equivalence row needs the imported cards and the pinned "
            "runtimes (s0-collect --texts and --sheet-runtime with --manifest; Codex review 2026-10-22 #13)")
    v3 = read_json(manifest_path) if manifest_path else None
    pinned = v3["data"] if v3 else None
    sheet_runtime = v3["runtime"]["spreadsheetbench"] if v3 else None
    rows, checks = {}, {}

    def row(name, fn):
        try:
            passed, evidence = fn()
        except Exception as error:  # noqa: BLE001 -- every failure of a row is that row's recorded failure
            passed, evidence = False, {"error": "%s: %s" % (type(error).__name__, error)}
        rows[name] = _record(root, name, passed, evidence)
        checks[name] = bool(passed)

    def pytest_row():
        found = prelaunch.zero_call_checks(snapshot, run=deps.run)
        return found["passed"], found

    def named(name):
        files, keyword = NAMED[name]
        found = named_tests(snapshot, files, keyword, run=deps.run)
        return found["passed"], found

    def escape():
        report = deps.escape_report() if deps.escape_report else escape_report(deps.docker, scratch)
        judged = {**smoke.escape_rows(report), **fixer9_rows(report)}
        return all(judged.values()), {"rows": judged, "dumpable": report["worker"]["dumpable"],
                                      "probe_sha256": hashlib.sha256(smoke.ESCAPE_PROBE.read_bytes()).hexdigest(),
                                      "report": report}

    def sheet():
        return sheet_row(deps, source=sheet_source, sha256=sheet_sha256, base_runtime=sheet_runtime,
                         engine_qualification=engine_qualification, fixtures_dir=fixtures_dir,
                         target=root / DIR / "sheet-fixture-qualification")

    def supply_row():
        return (deps.supply or _supply)(root, history_root, exclusion_check)

    inputs = fixtures.public_input_dirs(fixtures_dir, Path(tempfile.mkdtemp(prefix="execskill-s0-inputs-",
                                                                            dir=scratch)))
    row("pytest", pytest_row)
    row("equivalence", lambda: equivalence({b: p for b, p in items.items()}, cards=cards, runtimes=runtimes,
                                           alfworld_env=deps.alfworld_env, native=deps.native,
                                           precheck=deps.precheck))
    for name in ("exceptions", "ledger"):
        row(name, lambda name=name: named(name))
    row("sandbox", lambda: sandbox_row(deps, input_dirs=inputs, scratch=scratch,
                                       missing_docker=deps.extra.get("missing_docker")))
    row("escape_probe", escape)
    row("measurements", lambda: _measure(deps, pinned=pinned, selftest=selftest, item_files=items, scratch=scratch))
    row("determinism", lambda: _determinism(deps, items, scratch))
    row("replay", lambda: replay_row(read_json(traces), _workers(deps, scratch),
                                     **({"expected": deps.extra["d3_expected"]} if "d3_expected" in deps.extra
                                        else {})))
    row("supply", supply_row)
    row("sheet", sheet)
    for name in ("registry", "codex_fixtures"):
        row(name, lambda name=name: named(name))
    row("leftovers", lambda: _leftovers(deps))
    measured = rows["measurements"]["result"]
    if checks["measurements"]:  # the registered limits and the pins exist only from a passing measurement
        write_json(root / DIR / LIMITS_FILE, protocol.record(LIMITS_KIND, EVIDENCE, {
            "derived": measured["derived"], "measured": measured["measured"],
            "p99_workbook_bytes": measured["p99_workbook_bytes"], "registration": "A5-1 (registrar 2026-10-22)"}))
        write_json(safe_path(pins_out), measured["pins"])
    write_json(root / DIR / CHECKS, {"checks": checks})
    return {"checks": checks, "passed": all(checks.values())}


def sheet_row(deps, *, source, sha256, base_runtime, engine_qualification, fixtures_dir, target):
    """§10 S0 sheet row (ticket C7b1-3, registrar addendum 2026-10-22 12:0x): (passed, evidence). The v3 training
    qualification ``source`` re-verified against its pinned record hash ``sha256``; the SpreadsheetBench runtime of
    this snapshot's zero-call engine qualification (``qualify.engine_runtime(base_runtime, engine_qualification)``: the
    v3 block with only the three qualification fields replaced, revalidated offline); that engine compared with the v3
    training qualification's (``qualify.same_engine_sources`` against its ``recalculation.qualification_path``); the
    fixture workbooks qualified twice under the runtime into ``target``. Passes only if the import verifies, every
    fixture item qualifies and the engine sources are the same. ``deps`` may replace each part (fake mode)."""
    found = (deps.sheet_import or _sheet_import)(source, sha256)
    runtime = (deps.engine_runtime or qualify.engine_runtime)(base_runtime, engine_qualification)
    engine = runtime["recalculation"]
    same = (deps.same_sources or qualify.same_engine_sources)(engine["qualification_path"],
                                                               found["recalculation"]["qualification_path"])
    tasks = fixtures.load_items(fixtures_dir, "spreadsheetbench")
    made = (deps.qualify_fixtures or _qualify_fixtures)(tasks, target, runtime)
    listed = list(made.get("qualified") or ())
    qualified = sorted(listed) == sorted(t["task_id"] for t in tasks) and not made.get("excluded")
    return qualified and same["same"] is True, {
        "import": {key: found[key] for key in ("version", "summary")},
        "engine": {"qualification_path": engine["qualification_path"],
                   "qualification_sha256": engine["qualification_sha256"],
                   "qualification_hash": engine["qualification_hash"], "same_sources_as_v3_training": same},
        "fixtures": {"items": len(tasks), "qualified": len(listed), "excluded": made.get("excluded") or {},
                     "all_qualified": qualified, "record_sha256": made.get(protocol.RECORD_HASH)}}


def _sheet_import(source, sha256):
    found = qualify.load(source)
    require(found["side"] == "train", "The imported qualification is the training side's")
    qualify.reverify(found, pinned=sha256)
    return {"version": found["version"], "summary": qualify.summary(found), "recalculation": found["recalculation"]}


def _leftovers(deps):
    found = deps.leftovers()
    return found["verdict"] in ("clean", "cannot_judge"), found


def _qualify_fixtures(tasks, target, runtime):
    """The frozen v7 recalculating qualification of the fixture workbooks, twice each (``qualify.qualify`` with the
    runtime of ``qualify.engine_runtime``: v3's SpreadsheetBench block on this snapshot's engine qualification; S0
    runs alone, so the native pool is not shared)."""
    require(runtime is not None and runtime.get("spreadsheet_scorer") == qualify.SCORER,
            "The sheet row needs the SpreadsheetBench runtime of the v7 scorer")
    return qualify.qualify(tasks, target, runtime, side="train", native=SimpleNamespace(hold=nullcontext),
                           workers=3, evidence="engineering_fixture")


def _alfworld_cut(history_root):
    """The supply row's ALFWorld part: ``(passed, evidence)`` of the persisted supply (``make-items``), its registered
    cut and the cut's pre-reset views. Every slice is cut in full except the selection slice, an upper bound
    (``supply.UPTO``): its 20 rooms of at most ``MAX_GAMES_PER_ROOM`` games hold at most 100 of the registered 200, so
    the 108-room cut is 12 + 60 + 150 + 100 = 322, never ``sum(PRERESET_GAMES)`` = 422 (smoke S0 10/22 22:07)."""
    folder = safe_path(history_root) / "supply"
    alfworld = protocol.verified(read_json(folder / "alfworld-xs.json"), supply.RECORD_KIND)
    views = protocol.verified(read_json(folder / "alfworld-xs-views.json"), "alfworld-views")
    sizes = supply.registered_sizes("alfworld")
    cut = supply.slices("alfworld", supply.order("alfworld", alfworld["items"]), sizes)
    wanted = {i["task_id"] for part in cut.values() for i in part}
    views_ok = (views["supply_sha256"] == alfworld[protocol.RECORD_HASH] and set(views["views"]) == wanted
                and all(digest(v["view"]) == v["view_sha256"] for v in views["views"].values()))
    full = set(cut) == set(sizes) and all(len(cut[name]) <= size if name in supply.UPTO else len(cut[name]) == size
                                          for name, size in sizes.items())
    return views_ok and full, {"counts": alfworld["counts"], "preset": len(views["views"]), "cut": len(wanted),
                               "slices": {name: len(part) for name, part in sorted(cut.items())}}


def _supply(root, history_root, exclusion_check):
    """§10 S0 supply row on the persisted supply files (``make-items``) and exclusion records (``exclude-tests``)."""
    passed, alfworld = _alfworld_cut(history_root)
    tail = protocol.verified(read_json(safe_path(history_root) / "supply" / "searchqa-tail.json"), supply.RECORD_KIND)
    exclusion_check(root)
    kept = exclusion.apply_exclusion(tail["items"], root)
    tail_items = [i for i in tail["items"] if i["task_id"] in {k["task_id"] for k in kept["items"]}]
    accepted = supply.slices("searchqa", supply.order("searchqa", tail_items),
                             supply.registered_sizes("searchqa", "tail"), kept=kept)
    return passed, {"alfworld": alfworld,
                    "searchqa_tail": {"counts": tail["counts"], "kept": len(kept["items"]),
                                      "accept": len(accepted["accept"])}, "exclusion": "verified"}


