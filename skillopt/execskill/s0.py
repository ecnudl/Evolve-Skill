def pool_views(pinned):
    """{bench: {"items", "max", "p99"}} of the public-view bytes over the five training pools, plus {"workbook": ...}
    of the SpreadsheetBench workbook files. Each file of ``data.paths.train`` is checked against its pinned sha256 and
    read by the frozen ``datasets.load_panel`` / ``validate_panel``; the manifest's val and test paths are never
    opened (the frozen ``data.pool`` would open the val parts too)."""
    found, workbooks = {}, []
    for bench in protocol.BENCHES:
        path = safe_path(pinned["paths"]["train"][bench])
        require(pinned["sha256"].get(str(path)) == hashlib.sha256(path.read_bytes()).hexdigest(),
                "A training pool is not the pinned file: %s" % bench)
        panel = datasets.load_panel(str(path))
        datasets.validate_panel(panel)
        require(panel["benchmark"] == bench, "Panel benchmark mismatch: %s" % bench)
        sizes = []
        for item in panel["tasks"]:
            view, book = _view_size(bench, item, path.parent)
            sizes.append(view)
            if bench == "spreadsheetbench":
                workbooks.append(book)
        found[bench] = {"items": len(sizes), "max": max(sizes), "p99": smoke._p99(sizes)}
    found["workbook"] = {"items": len(workbooks), "max": max(workbooks), "p99": smoke._p99(workbooks)}
    return found


def limits(measured, *, mem_available_kib):
    """A5-1 (registrar 2026-10-22): {"limits": {kind: Limits fields}, "slots", "guard"} from ``measured`` (KiB and
    bytes: ``vsz_kib`` the largest worker VSZ, ``view_bytes_max`` the largest public view, ``native_peak_rss_kib``,
    ``worker_rss_kib`` and ``call_rss_kib`` the peak RSS of a live worker and of a call child)."""
    address = max(AS_FLOOR_MIB, _round_up(2 * measured["vsz_kib"] / KIB, AS_STEP_MIB))
    frame = max(FRAME_FLOOR, _round_up(2 * measured["view_bytes_max"], FRAME_STEP))
    native = 3 if measured["native_peak_rss_kib"] <= NATIVE_LOW_KIB else protocol.NATIVE_SLOTS_LOW_MEMORY
    slots = {**protocol.SANDBOX_SLOTS, "spreadsheet-native": native}
    peaks = {"execskill-sandbox-live": measured["worker_rss_kib"], "execskill-sandbox": measured["call_rss_kib"],
             "spreadsheet-native": measured["native_peak_rss_kib"]}
    budget = int(GUARD_SHARE * mem_available_kib)

    def total():
        return sum(slots[kind] * peaks[kind] for kind in peaks)

    steps = []
    for pool, reduced in GUARD_STEPS:
        if total() <= budget:
            break
        slots[pool] = reduced
        steps.append({pool: reduced})
    kinds = {kind: asdict(replace(value, address_space_mb=address, frame_bytes=frame))
             for kind, value in sorted(sandbox.LIMITS.items())}
    return {"limits": kinds, "slots": slots,
            "guard": {"sum_kib": total(), "budget_kib": budget, "mem_available_kib": mem_available_kib,
                      "steps": steps, "ok": total() <= budget}}


def native_peak(workbook, docker):
    """The native peak RSS in KiB (plan §5 memory rule): the solver program's shape on ``workbook`` in the pinned image
    with the frozen ``_native`` argv (``precheck.native_command``, 4 GiB, 1 CPU); the container removed by name."""
    from . import precheck

    with tempfile.TemporaryDirectory(prefix="execskill-native-peak-") as folder:
        root = Path(folder)
        root.chmod(0o755)
        (root / "worker.py").write_text(NATIVE_PROBE)
        (root / "input.xlsx").write_bytes(Path(workbook).read_bytes())
        for path in root.iterdir():
            path.chmod(0o444)
        name = precheck.container_name()
        try:
            done = docker.run(precheck.native_command(docker.binary, name, root, sandbox.IMAGE, 4096, 1),
                              NATIVE_SECONDS)
        finally:
            sandbox.cleanup(name, docker=docker)
    found = json.loads(done.stdout.decode("utf-8")) if done.code == 0 else {}
    require(found.get("returncode") == 0 and type(found.get("peak_rss_kib")) is int,
            "The native peak-RSS run failed (exit %s)" % done.code)
    return found["peak_rss_kib"]


