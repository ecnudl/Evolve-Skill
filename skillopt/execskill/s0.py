def d3_entries(traces):
    """The D3 traces (/data/feasibility/D3/r3/lt/traces.json: {chain, cell, item, token, initial, steps: [[action,
    observation]]}) as the hook inputs of ``replay.inputs_of``'s ALFWorld shape, an event after every step."""
    entries = []
    for trace in traces:
        steps, observation = [], trace["initial"]
        for i, (action, after) in enumerate(trace["steps"]):
            view = {"initial_observation": trace["initial"], "observation": observation, "admissible_commands": []}
            event = {"step": i, "action": action, "observation": str(after)[:replay.OBSERVATION_CHARS],
                     "admissible_commands": []}
            steps.append({"view": view, "action": action, "event": event})
            observation = after
        entries.append({"cell": "d3/%s/%s" % (trace["chain"], trace["cell"]), "bench": "alfworld",
                        "item": trace["item"], "token": trace["token"],
                        "view": supply.routing_view(trace["initial"], []), "request_view": None, "report": None,
                        "steps": steps})
    return entries


def replay_row(traces, workers, *, expected=(D3_TRAJECTORIES, D3_STEPS)):
    """§10 replay row: zero crash faults of ``fx-alf-tracker`` in two workers and the reference tracker over every
    step; the registered counts (228 trajectories, 7,524 steps)."""
    entries = d3_entries(traces)
    steps = sum(len(e["steps"]) for e in entries)
    tracker = fixtures.fixture_package().get("fx-alf-tracker")
    report, outcomes = replay.zero_crash(tracker, entries, workers)
    reference = 0
    for entry in entries:
        follow = replay.ReferenceTracker(entry["steps"][0]["view"]["initial_observation"])
        for step in entry["steps"]:
            follow.update(step["event"]["action"], step["event"]["observation"])
            reference += 1
    agree, compared = replay.reference_tracker_agreement({e["cell"]: e for e in entries}, outcomes)
    passed = report["passed"] and (len(entries), steps) == tuple(expected) and reference == steps
    return passed, {"trajectories": len(entries), "steps": steps, "zero_crash": report,
                    "reference_steps": reference, "agreement": [agree, compared], "expected": list(expected)}


