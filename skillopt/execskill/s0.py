def _mem_available_kib():
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemAvailable:"):
            return int(line.split()[1])
    raise ValueError("No MemAvailable in /proc/meminfo")


def _view_size(bench, item, base):
    """(view bytes, workbook bytes) of one training item: the routing view's canonical JSON (SpreadsheetBench with
    its workbook preview; ALFWorld the public view), and the workbook files on disk."""
    public = item["public"]
    files = [Path(p) if Path(p).is_absolute() else base / p for p in public.get("input_files") or []]
    view = public if bench == "alfworld" else solver.routing_view(bench, public, runtime=fixtures.SHEET_RUNTIME)
    size = len(json.dumps(view, sort_keys=True, ensure_ascii=False).encode("utf-8"))
    return size, sum(path.stat().st_size for path in files)


