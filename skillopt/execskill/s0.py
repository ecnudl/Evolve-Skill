def _call_child(docker, name, mode):
    done = docker.run([docker.binary, "exec", name, "python", "-s", "-B", "-c", CALL_CHILD, mode], 30)
    return done.stdout.decode("utf-8", "replace").strip()


def kill_child(docker, name):
    """SIGKILL the running call's child of container ``name`` through ``docker exec`` (an external kill, as the
    memory cgroup does it); a fake docker (``tests/execskill_fakes_docker.py``) kills its own."""
    if hasattr(docker, "kill_child"):
        return docker.kill_child(name)
    return _call_child(docker, name, "kill")


def kill_worker(docker, name):
    """SIGKILL the worker (the container's first process) through ``docker kill``, once the call's child runs."""
    if hasattr(docker, "kill_child"):
        docker.children(name)
        return docker.kill_worker(name)
    _call_child(docker, name, "wait")
    return docker.run([docker.binary, "kill", "--signal=KILL", name], 30).code


def sandbox_row(deps, *, input_dirs, scratch, missing_docker=None):
    """§10 S0 sandbox row with ``fixtures.sandbox_suite``: per case its outcome, healthy probes before and after."""
    suite, cases = fixtures.sandbox_suite()
    view = {"text": "fixture view"}
    padded = input_dirs[fixtures.cell("spreadsheetbench", "fx-spreadsheetbench-%02d" % fixtures.PADDED)]
    plain = sandbox.Worker(docker=deps.docker, scratch=scratch).start(suite, kind="cell")
    mounted = sandbox.Worker(docker=deps.docker, scratch=scratch).start(suite, kind="cell", inputs_dir=padded)
    outcomes, healthy = {}, True
    try:
        for case in cases:
            worker = mounted if case["inputs"] == "p99" else plain
            healthy &= worker.call(fixtures.HEALTHY, "applies", [view], timeout_s=2).get("value") is True
            out = {}

            def run(worker=worker, case=case, out=out):
                out["result"] = worker.call(case["id"], case["fn"], case["args"], timeout_s=case["timeout_s"])

            if case["action"] is None:
                run()
            else:
                thread = threading.Thread(target=run)
                thread.start()
                (kill_child if case["action"] == "kill_child" else kill_worker)(deps.docker, worker.names[-1])
                thread.join(120)
            result = out.get("result") or {}
            expected = case["expected"]
            ok = (result.get("ok") is False and result.get("fault") == expected["fault"]
                  if expected["class"] == "procedure_fault" else result.get("ok") is True)
            outcomes[case["id"]] = {"ok": ok, "fault": result.get("fault"), "expected": expected}
            healthy &= worker.call(fixtures.HEALTHY, "applies", [view], timeout_s=2).get("value") is True
        bookkeeping = plain.dropped == ["fx-sbx-worker-kill"] and plain.rejected == {"fx-sbx-banned": "policy:import"}
    finally:
        for worker in (plain, mounted):
            worker.close()
    missing = _image_missing(missing_docker or deps.docker, scratch)
    try:
        sandbox.drain_check(docker=deps.docker)
        drained = True
    except Exception as error:  # noqa: BLE001 -- CleanupUnconfirmed: recorded, the row fails
        drained = "%s: %s" % (type(error).__name__, error)
    passed = all(o["ok"] for o in outcomes.values()) and healthy and bookkeeping and missing and drained is True
    return passed, {"cases": outcomes, "healthy_probes": healthy, "dropped_and_rejected": bookkeeping,
                    "image_missing_is_unavailable": missing, "drained": drained,
                    "restarts": plain.restarts + mounted.restarts}


def _image_missing(docker, scratch):
    """A missing image is ``SandboxUnavailable``: a bogus digest on docker; a fake docker told its image is gone."""
    image = docker.image if hasattr(docker, "image_missing") else BOGUS_IMAGE
    worker = sandbox.Worker(docker=docker, scratch=scratch, image=image)
    worker.start(empty(step="smoke/s0", evidence=EVIDENCE), kind="cell")
    try:
        worker.ping()
    except SandboxUnavailable:
        return True
    finally:
        worker.close()
    return False


def escape_report(docker, scratch):
    """The escape probe once in the registered cell argv (``smoke.escape_argv``), its container removed by its exact
    name; the parsed report. SandboxUnavailable when docker is missing or the probe fails."""
    if docker.binary is None:
        raise SandboxUnavailable("sandbox_unavailable: docker not found on %s" % sandbox.DOCKER_ENV["PATH"])
    runner = Path(tempfile.mkdtemp(prefix="execskill-escape-", dir=scratch))
    for source in (sandbox.WORKER_FILE, sandbox.POLICY_FILE, smoke.ESCAPE_PROBE):
        (runner / source.name).write_bytes(source.read_bytes())
        (runner / source.name).chmod(0o444)
    runner.chmod(0o755)
    name = sandbox.PREFIX + uuid.uuid4().hex
    try:
        done = docker.run(smoke.escape_argv(runner, name=name, docker=docker.binary), smoke.ESCAPE_SECONDS)
    finally:
        sandbox.cleanup(name, docker=docker)
        for path in runner.iterdir():
            path.chmod(0o644)
            path.unlink()
        runner.rmdir()
    if done.code != 0:
        raise SandboxUnavailable("sandbox_unavailable: the escape probe exited with %s" % done.code)
    return json.loads(done.stdout.decode("utf-8"))


def fixer9_rows(report):
    """The escape rows of ticket fixer-9 item 2 (C5-3 item 8) from the probe's ``worker`` section: the real worker
    started in the pinned image is non-dumpable (``dumpable`` 0, recorded) and still answers after SIGINT; a call
    child is non-dumpable, leads its own process group, and its descendant is gone after the call."""
    worker, group = report["worker"], report["worker"]["group"]
    return {"dumpable": worker["dumpable"] == 0 and group["child_dumpable"] == 0,
            "sigint": worker["after_sigint"] == "answered",
            "process_group": group["child_pgid"] == group["child_pid"] != group["parent_pgid"]
            and group["descendant"] in ("gone", "zombie")}


