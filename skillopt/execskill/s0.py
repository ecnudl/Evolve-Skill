def named_tests(snapshot, files, keyword, *, run=subprocess.run, python=protocol.INTERPRETER):
    """One registered pytest selection on the snapshot (plan §8.1): {"command", "returncode", "summary", "passed"};
    passes on exit 0 with tests passed, none failed and none selected away to nothing."""
    command = [str(python), "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider", *files]
    command += ["-k", keyword] if keyword else []
    done = run(command, cwd=str(safe_path(snapshot)), env=prelaunch.launch_env(), stdout=subprocess.PIPE,
               stderr=subprocess.STDOUT, timeout=prelaunch.PYTEST_SECONDS, check=False)
    output = done.stdout.decode("utf-8", "replace") if isinstance(done.stdout, bytes) else str(done.stdout)
    lines = [line.strip() for line in output.splitlines() if prelaunch.SUMMARY.match(line.strip())]
    summary = lines[-1] if lines else ""
    return {"command": command, "returncode": done.returncode, "summary": summary,
            "passed": done.returncode == 0 and " passed" in summary and "failed" not in summary
            and "error" not in summary}


# ---------------------------------------------------------------------------------------------- equivalence
class _Transport:
    """The deterministic zero-call model of the equivalence row: a reply from the request alone (QA: an answer tag
    of the request's hash; SpreadsheetBench: ``COPY_PROGRAM`` in a python fence under a comment of the request's hash,
    which both extractions take and the native runner executes on every public case -- Codex #13: an unfenced reply
    made both sides the same code-delivery failure, no backend execution at all; ALFWorld: the first admissible
    command)."""

    def __init__(self, bench):
        self.bench, self.requests = bench, []

    def __call__(self, system, user):
        self.requests.append((system, user))
        key = hashlib.sha256((system + "\0" + user).encode("utf-8")).hexdigest()[:8]
        if self.bench == "alfworld":
            commands = json.loads(user).get("admissible_commands") or ["look"]
            text = "<action>%s</action>" % commands[0]
        elif self.bench == "spreadsheetbench":
            text = "```python\n# %s\n%s```" % (key, COPY_PROGRAM)
        else:
            text = "<answer>%s</answer>" % key
        tokens = len(user) // 4
        return {"ok": True, "response": text, "finish_reason": "stop", "status": 200,
                "usage": {"prompt_tokens": tokens, "completion_tokens": 8, "total_tokens": tokens + 8}}


def _steady(value):
    """``value`` without its measured ``wall_seconds`` (a native run's duration, never equal between two runs)."""
    if isinstance(value, dict):
        return {k: _steady(v) for k, v in value.items() if k != "wall_seconds"}
    if isinstance(value, list):
        return [_steady(v) for v in value]
    return value


def _executed(bench, prediction):
    """Codex #13: whether the frozen run's backend executed validly -- the prediction is available and, on
    SpreadsheetBench, every public case's program run generated its workbook (native status "available")."""
    if prediction.get("status") != "available":
        return False
    if bench != "spreadsheetbench":
        return True
    cases = (prediction.get("output") or {}).get("cases")
    return isinstance(cases, list) and bool(cases) and all(
        isinstance(case, dict) and case.get("status") == "available" for case in cases)


def _compare(bench, public, card, runtime):
    """One item's verdict: "excluded" (ALFWorld, a step not ``tag_exact``), "invalid" (Codex #13: the frozen run sent
    no solver request or its backend did not execute validly, ``_executed`` -- equal empty request lists and identical
    infrastructure failures prove nothing), else "same" or "different"."""
    frozen_call, shell_call = _Transport(bench), _Transport(bench)
    frozen = backends.solve(bench, public, card, frozen_call, runtime=runtime)
    routed = solver.solve(bench, public, card, empty(step="smoke/s0", evidence=EVIDENCE), shell_call, runtime=runtime)
    if bench == "alfworld" and any(s.get("how") != "tag_exact" for s in routed["shell"].get("alfworld_steps") or []):
        return "excluded"
    if not frozen_call.requests or not _executed(bench, frozen):
        return "invalid"
    same = (shell_call.requests == frozen_call.requests
            and _steady({k: v for k, v in routed.items() if k != "shell"}) == _steady(frozen)
            and [c["request_sha256"] for c in routed["shell"]["calls"]]
            == [_request_hash(s, u) for s, u in frozen_call.requests])
    return "same" if same else "different"


def equivalence(item_files, *, cards, runtimes, alfworld_env=None, native=None, precheck=None):
    """T-SOLVER-1 on the smoke items (§2.3, §10 S0): per bench, compared / same / different / excluded / invalid
    counts; passes when every compared item is the same, no item is invalid (``_compare``) and every bench compared at
    least one item. ``cards``: {bench: card text}, the imported cards (none blank); ``runtimes``: {bench: runtime},
    the pinned runtimes, one per bench (Codex #13); both are recorded by hash (``cards_sha256``,
    ``runtimes_sha256``). ``alfworld_env`` / ``native`` / ``precheck``: fakes for the frozen ALFWorld environment, the
    frozen native runner and the routed pre-check (rehearsal and tests only). A native run's measured
    ``wall_seconds`` is not compared (``_steady``)."""
    benches = sorted(item_files)
    require(isinstance(cards, dict) and all(type(cards.get(b)) is str and cards[b].strip() for b in benches),
            "S0's equivalence runs with the imported cards, none blank (Codex #13)")
    require(isinstance(runtimes, dict) and all(isinstance(runtimes.get(b), dict) for b in benches),
            "S0's equivalence runs with the pinned runtime of every bench (Codex #13)")
    found = {}
    patches = [mock.patch.object(module, name, fake) for module, name, fake in (
        (backends, "_new_alfworld", alfworld_env), (backends, "_native", native), (prechecks, "precheck", precheck))
        if fake is not None]
    with ExitStack() as stack:
        for patch in patches:
            stack.enter_context(patch)
        for bench in benches:
            counts = {"same": 0, "different": 0, "excluded": 0, "invalid": 0}
            for item in read_json(item_files[bench]):
                counts[_compare(bench, item["public"], cards[bench], runtimes[bench])] += 1
            found[bench] = {**counts, "compared": counts["same"] + counts["different"]}
    passed = all(v["different"] == 0 and v["invalid"] == 0 and v["compared"] > 0 for v in found.values())
    return passed, {"benches": found,
                    "cards_sha256": {b: hashlib.sha256(cards[b].encode("utf-8")).hexdigest() for b in benches},
                    "runtimes_sha256": {b: digest(runtimes[b]) for b in benches}}


