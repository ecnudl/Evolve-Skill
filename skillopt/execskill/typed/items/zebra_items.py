"""The ZebraLogic maker of the item stage (CHAIN-DECISIONS T5; brief P2, section D, first paragraph; BANK-PILOT B31 to
B35 for what was checked about these puzzles). No model is called.

Capability sheet (what the analyst may ask for): ``sizes`` -- the judged sizes present in the run's practice slices;
``emphasis`` -- per clue kind a factor in [0.5, 2.0] (default 1) that DIVIDES the kind's removal weight
(``zebra.REMOVAL_WEIGHTS``: a lighter kind is tried for removal later and stays in the puzzle more often, so a larger
factor keeps more clues of that kind); ``search`` -- 'any' or 'needed' (only puzzles the first solver does not settle
without search: more than one search node, the measure ``zebra.compare`` uses).

Which puzzles (the slots of one step, ``plan_slots``), per side (judging first, then shown):

- attack: per kept weakness in plan order, the counts of ``counts['attack_split']``; the n-th puzzle of a weakness takes
  the n-th of its spec's sizes in turn (all sizes of the sheet when its spec names none), its emphasis and its search;
  without kept weaknesses the attack puzzles are drawn like calibration puzzles (weakness None);
- guard: natural weights, the sizes where every learn item was right in all R runs, in turn; when there is no such
  size, the two sizes with the highest pass rate (right runs / (items * R), exact; ties: the earlier size in
  ``zebra_build.SIZES``);
- calibration (judging side only): natural weights, sizes in the proportion of the real gate slice (``items.
  largest_remainder``: ties to the larger gate count, then the earlier size), interleaved in turn.

How one puzzle is made (``make_slot``): the language is learned once per unit from the pinned practice pool exactly as
``zebra_build.stage_language`` does (both proofs must pass; its record ``zebralogic/language.json`` stays in the unit),
unless P2b hands in the step's language record. Attempt a = 1 .. MAX_ATTEMPTS: the seed names the version, chain, step,
round, side, class, weakness, number and attempt; the puzzle is made as ``zebra_build._made`` makes a bank puzzle
(Name first, the other columns drawn from the seed, ``zebra.make`` with the slot's weights); it is refused when its text
equals a pool puzzle's or an earlier made puzzle's of this chain (``RunRegistry.texts``), refused when ``zebra.certify``
fails (both solvers, the stored grid as the one solution, no removable clue), refused under 'needed' when the first
solver settles it without search; else its item is ``zebralogic.normalize`` of its row exactly as the bank makes it
(part 'made', origin 'made'), written, then its slot record. A made puzzle is its own family (its item id). A slot
whose attempts are all refused is a SHORTFALL: recorded, never filled with another class. Same inputs, same files.
"""
from __future__ import annotations

import hashlib
import random
from fractions import Fraction

from skillopt.continual_eval.core import require
from skillopt.execskill import zebralogic

from ..bank import zebra, zebra_build
from ..bank.env import text_sha256
from . import (RECORD_VERSION, identity_tag, item_record, item_sha256, made_counts, no_items, ordered_proportion)
from .store import slot_name

BENCH = 'zebralogic'
SIZES = zebra_build.SIZES
FIRST_COLUMN = zebra_build.FIRST_COLUMN
MAX_ATTEMPTS = 25          # attempts per slot; refused attempts (a duplicate text, no certificate, settled without
                           # search under 'needed') are recorded; a slot without a made puzzle after them is a shortfall
EMPHASIS_RANGE = [0.5, 2.0]
SEARCH = ('any', 'needed')
PART = 'made'              # the partition / part label of a made item (the bank's are 'bank')
ID_PREFIX = 'zm3-'         # + 16 hex digits of the seed's sha256: opaque, path-safe, unique per seed
SEED_TAG = 'typed-v3-items:zebralogic'
MAKER_RECORD = (BENCH, 'maker.json')
KIND_TEXT = {'found_at': 'X is in the n-th house', 'not_at': 'X is not in the n-th house',
             'same': 'X is Y (one house)', 'direct_left': 'X is directly left of Y',
             'left_of': 'X is somewhere to the left of Y', 'right_of': 'X is somewhere to the right of Y',
             'next_to': 'X and Y are next to each other', 'one_between': 'there is one house between X and Y',
             'two_between': 'there are two houses between X and Y'}
WHAT = ('New logic-grid puzzles are generated by fixed code the way the benchmark makes its own: a random grid, every '
        'true clue, clues removed in a weighted random order while the grid stays the only solution; every puzzle is '
        'certified by two exhaustive solvers (exactly one solution, no clue can be left out). Ask for puzzles by size '
        '(houses*attributes), by which clue kinds should stay more or less often, and by whether solving must need '
        'search (trial and error) rather than step-by-step deduction.')


def capability_sheet(sizes):
    """The sheet of this maker for the run's judged sizes (``sizes``: those present in its practice slices)."""
    found = [size for size in SIZES if size in set(sizes)]
    require(found and set(found) == set(sizes), 'Judged sizes of the ZebraLogic domain: %r' % (sorted(set(sizes)),))
    return {'maker': 'zebralogic-made-puzzles', 'what': WHAT, 'fields': {
        'sizes': {'kind': 'subset', 'values': found,
                  'meaning': 'sizes houses*attributes of the puzzles; leave out for every size of the list in turn'},
        'emphasis': {'kind': 'factors', 'keys': list(zebra.KINDS), 'range': list(EMPHASIS_RANGE), 'default': 1,
                     'kinds': dict(KIND_TEXT),
                     'meaning': ('per clue kind a factor in [0.5, 2.0]: above 1 the puzzle keeps more clues of that '
                                 'kind, below 1 fewer (default 1 for every kind)')},
        'search': {'kind': 'choice', 'values': list(SEARCH), 'default': 'any',
                   'meaning': ("'needed': only puzzles that step-by-step deduction alone does not solve (some "
                               "trial and error is needed); 'any': no such filter")}}}


def sizes_of(items):
    """The judged sizes of ``items`` (their ``task``), in ``SIZES`` order."""
    present = {item['task'] for item in items}
    require(present <= set(SIZES), 'Items of the judged ZebraLogic sizes')
    return [size for size in SIZES if size in present]


def guard_sizes(learn_items, outcomes, repeats, allowed):
    """(sizes, rule) of the guard puzzles: the sizes (in ``SIZES`` order, among ``allowed``) where every learn item
    was right in all R runs ('all_right'); else the two sizes with the highest pass rate (right runs over items * R,
    exact fractions; ties: the earlier size), 'two_highest'."""
    tally = {}
    for item in learn_items:
        size = item['task']
        if size in allowed:
            row = tally.setdefault(size, [0, 0])
            row[0] += 1
            row[1] += sum(outcome is True for outcome in outcomes[item['task_id']])
    require(tally, 'Learn items of the sheet sizes')
    right = [size for size in SIZES if size in tally and tally[size][1] == tally[size][0] * repeats]
    if right:
        return right, 'all_right'
    ranked = sorted(tally, key=lambda size: (-Fraction(tally[size][1], tally[size][0] * repeats), SIZES.index(size)))
    return [size for size in SIZES if size in ranked[:2]], 'two_highest'


def seed_of(identity, side, cls, weakness, number, attempt):
    return '%s:%s:%s:%s:%s:%d:%d' % (SEED_TAG, identity_tag(identity), side, cls, weakness or 'x', number, attempt)


def item_id_of(seed):
    return ID_PREFIX + hashlib.sha256(seed.encode('utf-8')).hexdigest()[:16]


def weights_of(emphasis):
    """The removal weights of a slot: None (``zebra.REMOVAL_WEIGHTS`` itself) without emphasis, else each kind's weight
    divided by its factor (1 when not named)."""
    if not emphasis:
        return None
    return {kind: zebra.REMOVAL_WEIGHTS[kind] / emphasis.get(kind, 1) for kind in zebra.KINDS}


def make_puzzle(language, size, seed, emphasis):
    """One puzzle of ``size`` from ``seed``, made as ``zebra_build._made`` makes a bank puzzle: Name first, then
    ``columns - 1`` other columns drawn from the seeded stream (among the columns the language has for this house
    count), then ``zebra.make`` on the same stream with the slot's weights."""
    houses, columns = (int(part) for part in size.split('*'))
    rng = random.Random(seed)
    others = sorted(name for name in language['columns']
                    if name != FIRST_COLUMN and str(houses) in language['columns'][name]['values'])
    require(FIRST_COLUMN in language['columns'] and len(others) >= columns - 1,
            'The language has the columns of size ' + size)
    names = [FIRST_COLUMN] + rng.sample(others, columns - 1)
    return zebra.make(rng, houses, names, language, weights_of(emphasis))


def plan_slots(plan, counts, sheet_sizes, gate_items, guard):
    """The slots of one step, in order (see the module text): ``[{'slot', 'side', 'class', 'weakness', 'number',
    'size', 'emphasis', 'search'}]``. ``gate_items``: the real gate slice; ``guard``: ``guard_sizes`` output."""
    by_id = {w['id']: w for w in plan['weaknesses']}
    gate = [(size, sum(item['task'] == size for item in gate_items)) for size in sheet_sizes]
    guard_list = guard[0]
    slots = []

    def add(side, cls, weakness, number, size, emphasis, search):
        slots.append({'slot': slot_name(side, cls, weakness, number), 'side': side, 'class': cls,
                      'weakness': weakness, 'number': number, 'size': size, 'emphasis': dict(emphasis),
                      'search': search})
    for side in ('judging', 'shown'):
        split = counts['attack_split'][side]
        if split:
            for weakness, count in split:
                require(weakness in by_id, 'The attack split names a kept weakness of the plan: ' + str(weakness))
                spec = by_id[weakness]['spec']
                sizes = [size for size in sheet_sizes if size in (spec.get('sizes') or sheet_sizes)]
                require(sizes, 'A weakness of the sheet sizes')
                for number in range(1, count + 1):
                    add(side, 'attack', weakness, number, sizes[(number - 1) % len(sizes)], spec.get('emphasis') or {},
                        spec.get('search', 'any'))
        else:
            for number, size in enumerate(ordered_proportion(counts[side]['attack'], gate), 1):
                add(side, 'attack', None, number, size, {}, 'any')
        for number in range(1, counts[side]['guard'] + 1):
            add(side, 'guard', None, number, guard_list[(number - 1) % len(guard_list)], {}, 'any')
        if side == 'judging':
            for number, size in enumerate(ordered_proportion(counts[side]['calibration'], gate), 1):
                add(side, 'calibration', None, number, size, {}, 'any')
    return slots


class ZebraMaker:
    """The ZebraLogic maker (``MAKERS['zebralogic']``)."""

    bench = BENCH
    built = True

    def capability_sheet(self, *, pool, learn_ids, gate_ids):
        by_id = {item['task_id']: item for item in pool}
        return capability_sheet(sizes_of([by_id[i] for i in list(learn_ids) + list(gate_ids)]))

    def public_kind(self, item):
        """What the analyst is told beside a learn item's text: its size."""
        return {'size': item['task']}

    def language(self, inp):
        """The step's language record: the one P2b hands in (it must be of this pool), else learned into the store
        (``zebra_build.stage_language``: both proofs on the pool, write-once ``zebralogic/language.json``)."""
        if inp.language is not None:
            found = inp.language
            require(found.get('version') == zebra_build.LANGUAGE_VERSION and found.get('pool') == dict(inp.pool_pin)
                    and found.get('pool_items') == len(inp.pool), 'The language record is of this pool')
            return found
        return zebra_build.stage_language(inp.store, inp.pool, inp.pool_pin)

    def make(self, inp):
        """Make the step's puzzles (see the module text). Returns ``{'bench', 'status': 'made' | 'no_items', 'reason',
        'records': [item records of made puzzles, slot order], 'slots': [one row per slot], 'shortfalls': [...],
        'made_counts', 'record'}``; the maker's record is also written once as ``zebralogic/maker.json``."""
        inp.check()
        require(inp.bench == BENCH, 'The ZebraLogic maker makes ZebraLogic items')
        if not any(inp.counts[side][name] for side in ('judging', 'shown') for name in inp.counts[side]):
            return no_items(inp, 'no_quota')
        language = self.language(inp)
        by_id = {item['task_id']: item for item in inp.pool}
        learn = [by_id[i] for i in inp.learn_ids]
        sheet = self.capability_sheet(pool=inp.pool, learn_ids=inp.learn_ids, gate_ids=inp.gate_ids)
        sheet_sizes = sheet['fields']['sizes']['values']
        guard = guard_sizes(learn, inp.outcomes, inp.repeats, sheet_sizes)
        slots = plan_slots(inp.plan, inp.counts, sheet_sizes, [by_id[i] for i in inp.gate_ids], guard)
        pool_texts = {text_sha256(item['public']['question']): item['task_id'] for item in inp.pool}
        made = {'version': language['version'], 'pool_sha256': language['pool']['sha256']}
        records, rows, shortfalls = [], [], []
        for slot in slots:
            stored = inp.store.slot(slot['slot'])
            if stored is None:
                stored = self.make_slot(inp, slot, language, pool_texts, made)
            else:
                self.check_stored(inp, slot, stored)
            record = stored['record']
            if record is not None:
                inp.registry.add(record)
                records.append(record)
            else:
                shortfalls.append({'slot': slot['slot'], 'side': slot['side'], 'class': slot['class'],
                                   'weakness': slot['weakness'], 'size': slot['size'], 'reason': stored['shortfall']})
            rows.append({'slot': slot['slot'], 'side': slot['side'], 'class': slot['class'],
                         'weakness': slot['weakness'], 'size': slot['size'],
                         'item': record['item'] if record else None, 'shortfall': stored['shortfall'],
                         'attempts': len(stored['attempts'])})
        maker = {'version': RECORD_VERSION, 'bench': BENCH, 'identity': dict(inp.identity), 'max_attempts': MAX_ATTEMPTS,
                 'language': {key: language[key] for key in ('version', 'pool', 'pool_items', 'checks')},
                 'sheet_sizes': sheet_sizes, 'guard_sizes': {'sizes': guard[0], 'rule': guard[1]},
                 'gate_sizes': [[size, sum(by_id[i]['task'] == size for i in inp.gate_ids)] for size in sheet_sizes],
                 'counts': {side: dict(inp.counts[side]) for side in ('judging', 'shown')},
                 'attack_split': inp.counts['attack_split'], 'slots': rows, 'shortfalls': shortfalls}
        stored = inp.store.once(MAKER_RECORD, lambda: maker)
        require(stored == maker, 'The maker record of this unit is of other inputs')
        return {'bench': BENCH, 'status': 'made', 'reason': None, 'records': records, 'slots': rows,
                'shortfalls': shortfalls, 'made_counts': made_counts(records), 'record': maker}

    @staticmethod
    def detail(slot):
        return {key: slot[key] for key in ('side', 'class', 'weakness', 'number', 'size', 'emphasis', 'search')}

    def check_stored(self, inp, slot, stored):
        """A slot record read back on resume: of this slot's spec, and (made) its item file of the recorded hash."""
        require(stored['detail'] == self.detail(slot), 'The stored slot %s was made for another spec' % slot['slot'])
        if stored['record'] is not None:
            item = inp.store.item(slot['slot'])
            require(item_sha256(BENCH, item) == stored['record']['item_sha256'],
                    'The item of slot %s is not the one its record certifies' % slot['slot'])

    def make_slot(self, inp, slot, language, pool_texts, made):
        """Make one slot (see the module text) and write its item and its slot record."""
        attempts = []
        for attempt in range(1, MAX_ATTEMPTS + 1):
            seed = seed_of(inp.identity, slot['side'], slot['class'], slot['weakness'], slot['number'], attempt)
            item_id = item_id_of(seed)
            row = zebra.row_of(make_puzzle(language, slot['size'], seed, slot['emphasis']), language, item_id)
            text = text_sha256(row['puzzle'])
            refused = ('pool_text' if text in pool_texts else 'made_text' if text in inp.registry.texts
                       else 'made_id' if item_id in inp.registry.ids else None)
            if refused is None:
                try:
                    certificate = zebra.certify(row, language)
                except ValueError as error:
                    refused, detail = 'not_certified', str(error)[:120]
                else:
                    if slot['search'] == 'needed' and certificate['search_nodes'] <= 1:
                        refused = 'settled_without_search'
            if refused is not None:
                attempts.append({'attempt': attempt, 'seed': seed, 'refused': refused,
                                 **({'detail': detail} if refused == 'not_certified' else {})})
                continue
            item = {**zebralogic.normalize(row, partition=PART), 'part': PART, 'origin': 'made', 'dataset_revision': None}
            require(item['task_id'] == item_id and item['task'] == slot['size'], 'The benchmark reads the made row as made')
            record = item_record(item=item_id, cls=slot['class'], weakness=slot['weakness'], side=slot['side'],
                                 family=item_id, source='made',
                                 certificate={'seed': seed, 'attempt': attempt, 'size': slot['size'],
                                              'emphasis': dict(slot['emphasis']), 'search': slot['search'],
                                              'text_sha256': text, 'language': dict(made), **certificate},
                                 item_sha256=item_sha256(BENCH, item))
            inp.store.write_item(slot['slot'], item)
            attempts.append({'attempt': attempt, 'seed': seed, 'made': item_id})
            return inp.store.write_slot(slot['slot'], record=record, shortfall=None, attempts=attempts,
                                        detail=self.detail(slot))
        return inp.store.write_slot(slot['slot'], record=None, shortfall='attempts_exhausted', attempts=attempts,
                                    detail=self.detail(slot))
