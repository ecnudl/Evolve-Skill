def _sheet_oracle(family, a):
    x,y,z,u,v,w = (a[f"A{i}"] for i in range(1,7))
    if family == SHEET_DEV[0]:
        low = x if x < y else y
        high = x-low
        b = [low, high, low*z, high*u]
        c = [low*z+high*u+v, x*w]
    elif family == SHEET_DEV[1]:
        cel = (x-32)/1.8
        kel = cel+273.15
        b = [cel,kel,kel*y,kel*y+z]
        c = [b[3],b[3]*u+v-w]
    elif family == SHEET_DEV[2]:
        volume = x*1000-y if x*1000 > y else 0
        stored = volume if volume < z*1000 else z*1000
        b = [volume,stored,stored*u,stored*u*v]
        c = [stored*u*v/1000,(volume-stored)*w]
    elif family == SHEET_DEV[3]:
        first_waste = x*(1-y)
        second_waste = x*y*(1-z)
        kept = x-first_waste-second_waste
        b = [x-first_waste,kept,first_waste,second_waste]
        c = [kept+(first_waste+second_waste)*u,x*v*w]
    elif family == SHEET_FINAL[0]:
        area = u*(2*x*y+y*y)
        b = [x+y,area,area*z,area*z*v*w]
        c = [b[3],area*(z+1)]
    elif family == SHEET_FINAL[1]:
        first_lost = x*y
        second_lost = (x-first_lost)*z
        b = [x-first_lost,x-first_lost-second_lost,first_lost+second_lost,x-first_lost-second_lost+u]
        c = [b[3]*v,x*w]
    elif family == SHEET_FINAL[2]:
        branch = y if y > z else z
        worker = x+y+z+u
        b = [branch,x+branch+u,worker,worker*v]
        c = [x+branch+u,worker*v*w]
    elif family == SHEET_FINAL[3]:
        lower, upper = z+(u-z)*x, v+(w-v)*x
        b = [lower,upper,lower+(upper-lower)*y,upper-lower]
        c = [b[2],lower+upper]
    elif family == SHEET_FINAL[4]:
        parallel = 1/(1/x+1/y)
        current = u/(parallel+z)
        b = [parallel,parallel+z,current,current*u*v]
        c = [b[3],parallel*w]
    elif family == SHEET_FINAL[5]:
        missing = x-y if x > y else 0
        rate = z-u
        duration = 0 if missing == 0 else -1 if rate <= 0 else missing/rate
        b = [missing,rate,duration,-1 if duration < 0 else duration+v]
        c = [b[3],rate*w]
    elif family == SHEET_FINAL[6]:
        ledger = x+y-z
        discrepancy = u-ledger
        b = [ledger,discrepancy,discrepancy*v,u]
        c = [discrepancy*v,0]
    else:
        capital_days = x*z+y*u
        b = [x*z,y*u,capital_days,(x*z/w+y*u/w)*v]
        c = [b[3],0]
    return {**{f"B{i+1}":value for i,value in enumerate(b)},"C1":c[0],"C2":c[1]}


def _sheet(family, split="development", *, smoke=False):
    description, formulas, defects, _, probes, statements = _SHEET[family]
    identifier = f"v14-sheet-{'smoke-' if smoke else ''}{split}-{family}"
