def _code_oracle(family, data):
    values, k = data["values"], data["k"]
    if family == CODING_DEV[0]:
        quotas = [Fraction(k*x, sum(values)) for x in values] if sum(values) else [Fraction(0) for _ in values]
        result = [int(q) for q in quotas]
        for i in sorted(range(len(values)), key=lambda i: (-(quotas[i]-int(quotas[i])), i))[:k-sum(result) if sum(values) else 0]:
            result[i] += 1
    elif family == CODING_DEV[1]:
        candidates = [(sum(values[i:i+k]), -i) for i in range(len(values)-k+1)] if 0 < k <= len(values) else []
        best = max(candidates) if candidates else (0, 1)
        result = [-best[1], best[0]]
    elif family == CODING_DEV[2]:
        rows = [values[i:i+k]+[0]*max(0, k-len(values[i:i+k])) for i in range(0, len(values), k)] if k else []
        result = [list(column) for column in zip(*rows)] if rows else []
    elif family == CODING_DEV[3]:
        result = []
        for sign, group in itertools.groupby(values, key=lambda x: (x > 0)-(x < 0)):
            items = list(group)
            if len(items) >= k:
                result.append([sign, len(items), sum(items)])
    elif family == CODING_FINAL[0]:
        result = next((x for x in set(values) if values.count(x) > len(values)/2), None)
    elif family == CODING_FINAL[1]:
        result = max([0]+[j-i for i in range(len(values)) for j in range(i+1,len(values)+1)
                          if values[i:j].count(0) == values[i:j].count(1)])
    elif family == CODING_FINAL[2]:
        result = [next((j for j in range(i+1,len(values)) if values[j] > x), -1) for i,x in enumerate(values)]
    elif family == CODING_FINAL[3]:
        result = next((i for i in range(1,len(values)+1) if values[:i]*(len(values)//i) == values), 0)
    elif family == CODING_FINAL[4]:
        frontier, result = {0}, 0 if k == 0 else -1
        for n in range(1,k+1):
            frontier = {x+coin for x in frontier for coin in values if x+coin <= k}
            if k in frontier:
                result = n
                break
    elif family == CODING_FINAL[5]:
        initial = max([0]+[-sum(values[:i]) for i in range(1,len(values)+1)])
        result = [initial, initial+sum(values)]
    elif family == CODING_FINAL[6]:
        result = any(sum(x for x,chosen in zip(values, mask) if chosen) <= k and
                     sum(x for x,chosen in zip(values, mask) if not chosen) <= k
                     for mask in itertools.product((False, True), repeat=len(values)))
    else:
        result = [x for _,x in sorted((-values.count(x),x) for x in set(values))]
    return {"result": result, "input_count": len(values), "input_sum": sum(values)}


def _coding(family, split="development", *, smoke=False):
    description, body, edits, regular, probes, statements = _CODE[family]
    source = "def run(data):\n" + "".join("    "+line+"\n" for line in _source(body).splitlines())
    source += "    return {'result':result,'input_count':len(values),'input_sum':sum(values)}\n"
    identifier = f"repo-v14-{'smoke-' if smoke else ''}{split}-{family}"
    scope = "full_replacement" if family == CODING_FINAL[7] else "partial_update"
    meta = _metadata("coding", family, split, smoke, scope)
    meta["obligations"] = _obligations(statements)
    cases = [{"label": f"{identifier}-case{i}", "input": data, "expected": _code_oracle(family,data),
              "exception": None, "public": i < 2, "dimension": "requested_behavior"}
             for i,data in enumerate(_pairs(regular))]
    mutants = []
    for before,after in edits:
        if source.count(before) != 1:
            raise ValueError("Ambiguous authored Coding mutation")
        mutants.append({"api.py": ENTRY, "logic.py": source.replace(before,after,1)})
    meta["counterexample_probe_pool"] = [
        {"id": f"{identifier}-probe{i}", "input": data, "expected": _code_oracle(family,data),
         "obligation_id": f"o{i}", "mutant": mutants[i]}
        for i,data in enumerate(_pairs(probes))]
    low = 0 if family in {CODING_DEV[0],CODING_FINAL[1],CODING_FINAL[4],CODING_FINAL[6]} else -50
    low = 1 if family == CODING_FINAL[4] else low
    domain = {"type":"object", "properties":{"values":{"type":"array","items":{"type":"integer","minimum":low,"maximum":100},"maxItems":12},
               "k":{"type":"integer","minimum":0,"maximum":100}}, "required":["values","k"],"additionalProperties":False}
    reference = {"api.py":ENTRY,"logic.py":source}
    starter = source
    for before, after in edits:
        starter = starter.replace(before, after, 1)
    meta["authored_starter_fault_count"] = len(edits)
    return CodingAdapter(RepoTask(id=identifier,split=split,family=family,cluster_id="v14-coding-"+family,
        prompt="Repair logic.py. "+description+" Return a dict with result, input_count, and input_sum. "
               "Audit fields are the ORIGINAL length and signed sum. Keep api.py unchanged and never mutate data.",
        files={"api.py":ENTRY,"logic.py":starter},reference_files=reference,editable_paths=["logic.py"],input_domain=domain,
        public_cases=cases[:2],private_cases=cases[2:],metadata=meta))


