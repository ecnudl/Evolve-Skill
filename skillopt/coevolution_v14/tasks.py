def payload(adapter):
    """Host-only; includes reference/probe definitions. Never solver projection."""
    return adapter.task.to_dict() if isinstance(adapter,CodingAdapter) else deepcopy(adapter.task)


def _development(adapter):
    row = payload(adapter)
    if row["split"] != "development" or row["metadata"].get("partition") != "development":
        raise ValueError("Only development tasks can expose obligations or probes")
    if row["metadata"].get("source_task_id"):
        raise ValueError("Probe tasks cannot recursively provide further probes")
    return row


def constraints_for(adapter):
    return deepcopy(_development(adapter)["metadata"]["obligations"])


def public_payload(adapter):
    from skillopt.coevolution_v8.feedback_study import public_task

    result = public_task(adapter)
    result["domain"] = adapter.domain
    row = payload(adapter)
    if adapter.domain == "coding":
        result["contract"] = deepcopy(row["metadata"]["contract"])
    if row["split"] == "development" and not row["metadata"].get("source_task_id"):
        result["obligations"] = constraints_for(adapter)
    return result


def probe_adapter(adapter):
    """Four separate challenge cases, never training/final fixtures or references."""
    row = _development(adapter)
    probes = row["metadata"]["counterexample_probe_pool"]
    if len(probes) != 4 or len({p["obligation_id"] for p in probes}) != 4:
        raise ValueError("Exactly four distinct authored obligation probes are required")
    identifier = row["id"]+"-dev-probe"
    meta = deepcopy(row["metadata"])
    meta.update(source_task_id=row["id"],source_task_hash=digest(row),counterexample_probe_pool=[],
                case_obligations={p["id"]:p["obligation_id"] for p in probes})
    if isinstance(adapter,CodingAdapter):
        cases = [{"label":p["id"],"input":deepcopy(p["input"]),"expected":deepcopy(p["expected"]),
                  "exception":None,"public":True,"dimension":"requested_behavior","obligation_id":p["obligation_id"]}
                 for p in probes]
        return CodingAdapter(replace(RepoTask.from_dict(row),id=identifier,public_cases=cases,private_cases=[],metadata=meta))
    row.update(id=identifier,metadata=meta,public_cases=[{"id":p["id"],"overrides":deepcopy(p["input"]),
        "expected":deepcopy(p["expected"]),"obligation_id":p["obligation_id"]} for p in probes],hidden_cases=[])
    return NativeAdapter(row)


